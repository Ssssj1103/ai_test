# -*- coding: utf-8 -*-
"""Day 23 · 边界用例生成器：四类边界 × 判定建议 = 标注规范第④部分的素材
运行方式：
    /Users/zcb/miniconda3/envs/aiml/bin/python day02_edge_cases.py
产出：data/day02_boundary_cases.md（直接粘贴进《标注规范 v1》第④部分）
核心思想：规范的灵魂是边界——每条边界用例都必须沉淀成"可执行的判定规则"。
"""

# ============ 导入区 ============
from itertools import product                 # 笛卡尔积：批量组合边界素材

# ============ ① 四类边界生成器 ============
# 每类 = 素材模板列表 + (建议判定, 规则表述)。规则表述就是规范④的正文素材。

MIXED = [                                     # 类型1：混合意图（测仲裁规则）
    ("再不发货我就去投诉你们", "催发货",
     "有投诉词但诉求核心是催进度 → 仲裁优先级：催发货 > 投诉"),
    ("我要退货，你们客服态度还特别差", "售后退换",
     "退货是主诉求，态度不满是伴随描述 → 售后退换 > 投诉"),
    ("东西烂了必须赔，不然我就退", "投诉",
     "赔偿诉求在前+退货是威胁手段 → 投诉 > 售后退换"),
    ("问下怎么投诉快递员", "咨询",
     "询问'怎么投诉'的流程 = 咨询投诉方法，本人未表达不满 → 咨询"),
]

EMOTION = [                                   # 类型2：情绪干扰（情绪词 ≠ 类别依据）
    ("不是说你们不好，就是问问能不能快点发", "催发货",
     "有情绪词但已澄清无不满 → 判事实诉求，不判投诉"),
    ("哈哈你们发货真是我见过最慢的", "催发货",
     "调侃语气但有具体问题（慢）→ 按事实判，语气降权"),
    ("呵呵，行，你们继续这样", "投诉",
     "冷淡+指代未解决的问题 → 结合上下文视为不满表达"),
]

NONSENSE = [                                  # 类型3：无语义/乱码（判定=其他 + 标记疑似无效）
    ("啊啊啊啊啊啊", "其他（疑似无效）",
     "无实义 → 归其他，同时打 invalid_suspect 标记供抽检"),
    ("123321123", "其他（疑似无效）", "纯数字无诉求 → 同上"),
    ("??????", "其他（疑似无效）", "标点堆叠 → 同上"),
]

OFFTOPIC = [                                  # 类型4：场景外（判定=无效不入集）
    ("帮我写一首关于快递的诗", "无效：不入集",
     "与电商客服业务无关 → 不入训练集，只记录"),
    ("今天天气怎么样", "无效：不入集", "闲聊无业务语义 → 不入集"),
]

ALL = [("混合意图", MIXED), ("情绪干扰", EMOTION),
       ("无语义/乱码", NONSENSE), ("场景外", OFFTOPIC)]

# ============ ② 导出边界规则文档（规范④素材） ============
lines = ["# 边界用例与判定规则（Day23）\n",
         "> 用途：《意图分类标注规范 v1》第④部分素材。每条边界 = 用例 + 判定 + 规则。\n"]
total = 0
for cat, cases in ALL:                        # 按类型输出
    lines.append(f"\n## 边界类型：{cat}\n")
    for i, (msg, verdict, rule) in enumerate(cases, 1):
        total += 1
        lines.append(f"{i}. **用例**：「{msg}」")
        lines.append(f"   - 判定：{verdict}")
        lines.append(f"   - 规则：{rule}")
lines.append(f"\n---\n共 {total} 条边界用例。使用纪律：逐条人工复核后再入规范；"
             "复核时不同意的条目要写明理由（分歧即新的边界盲区）。")

import os
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
out = os.path.join(root, "data", "day02_boundary_cases.md")
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(f"① 生成边界用例 {total} 条（四类）")
print(f"② 规范素材已导出：{out}")
print("\n③ 下一步（人工，不可跳过）：")
print("   a. 逐条复核判定建议——同意/不同意都要留痕")
print("   b. 把同意的规则粘进《标注规范 v1》第④部分")
print("   c. 不同意的条目 = 你发现了新的边界盲区，补规则")
